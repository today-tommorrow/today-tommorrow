-- DBA prerequisite: CREATE EXTENSION IF NOT EXISTS vector;
-- Dedicated namespace; no edits to pre-existing application tables.
CREATE SCHEMA IF NOT EXISTS work24_bge;
CREATE TABLE IF NOT EXISTS work24_bge.embedding_profile (
  profile_id text PRIMARY KEY CHECK (length(profile_id)=64),
  config jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS work24_bge.dataset_snapshot (
  dataset_id text PRIMARY KEY,
  profile_id text NOT NULL REFERENCES work24_bge.embedding_profile(profile_id),
  manifest jsonb NOT NULL,
  loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS work24_bge.course (
  course_id text NOT NULL,
  tme text NOT NULL,
  metadata jsonb NOT NULL,
  PRIMARY KEY(course_id,tme)
);
CREATE TABLE IF NOT EXISTS work24_bge.course_unit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_key text NOT NULL UNIQUE CHECK (length(unit_key)=64),
  course_id text NOT NULL,
  tme text NOT NULL,
  vector_row integer NOT NULL CHECK(vector_row>=0),
  unit_type text NOT NULL,
  ncs_unit_code text NOT NULL,
  unit_name text NOT NULL,
  embed_text text NOT NULL,
  text_sha256 text NOT NULL CHECK(length(text_sha256)=64),
  hours double precision CHECK(hours IS NULL OR hours>=0),
  source text,
  is_noise boolean NOT NULL CHECK(is_noise=false),
  is_inferred boolean NOT NULL,
  provenance jsonb NOT NULL,
  embedding vector(1024) NOT NULL,
  profile_id text NOT NULL REFERENCES work24_bge.embedding_profile(profile_id),
  dataset_id text NOT NULL REFERENCES work24_bge.dataset_snapshot(dataset_id),
  active boolean NOT NULL DEFAULT true,
  FOREIGN KEY(course_id,tme) REFERENCES work24_bge.course(course_id,tme)
);
CREATE INDEX IF NOT EXISTS course_unit_course_idx ON work24_bge.course_unit(course_id,tme);
CREATE INDEX IF NOT EXISTS course_unit_snapshot_idx ON work24_bge.course_unit(profile_id,dataset_id) WHERE active;

